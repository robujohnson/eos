#!/usr/bin/env python3
"""Fetch Finnish FACEIT CS2 ELOs for the /eos/faceit/ page -> faceit.js.

Needs a FACEIT Data API server-side key in the FACEIT_API_KEY env var
(free: https://developers.faceit.com -> App Studio -> API keys).

What it fetches:
  * the top TOP_N players of the FACEIT CS2 EU ranking with country = Finland
  * every EOS 14 player (from data.js): their FACEIT ELO, level and
    Finnish rank. Nicknames are taken from faceit-names.js when given,
    otherwise the in-game name is tried as the FACEIT nickname.

Run by .github/workflows/update-faceit.yml once a day.
FACEIT_API_BASE can point at a test server.
"""

import json
import os
import re
import sys
import time
from datetime import datetime, timezone
from zoneinfo import ZoneInfo
from urllib.error import HTTPError
from urllib.parse import quote, urlencode
from urllib.request import Request, urlopen

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
EOS_DATA = os.path.join(ROOT, 'data.js')
NAMES = os.path.join(ROOT, 'faceit-names.js')
OUT = os.path.join(ROOT, 'faceit.js')            # top FIRST_N + EOS players + meta (loaded with the page)
OUT_REST = os.path.join(ROOT, 'faceit-all.js')    # rest of the Finnish ranking (loaded on 'Show more' / search)
FIRST_N = 50
# ELOs at the end of the previous day (Finnish time). The +/- column compares with this,
# so it means 'change since yesterday' no matter how many times a day the job runs.
BASE = os.path.join(ROOT, 'faceit-base.json')
API = os.environ.get('FACEIT_API_BASE', 'https://open.faceit.com/data/v4').rstrip('/')
KEY = os.environ.get('FACEIT_API_KEY', '')
TOP_N = 1000
PAGE = 100  # max page size of the rankings endpoint


def get(path, **params):
    url = API + path + ('?' + urlencode(params) if params else '')
    req = Request(url, headers={'Authorization': 'Bearer ' + KEY, 'Accept': 'application/json'})
    for attempt in range(4):
        try:
            with urlopen(req, timeout=30) as r:
                return json.load(r)
        except HTTPError as e:
            if e.code == 404:
                return None
            if e.code == 429 or e.code >= 500:
                time.sleep(2 ** attempt)
                continue
            raise
    raise RuntimeError('FACEIT API kept failing for ' + url)


def read_js_object(path, var):
    with open(path, encoding='utf-8') as f:
        txt = f.read()
    m = re.search(r'window\.' + var + r'\s*=\s*(\{.*\})\s*;', txt, re.S)
    return json.loads(m.group(1)) if m else {}


def eos_data():
    d = read_js_object(EOS_DATA, 'EOS_DATA')
    h = d['leaderboard']['h']
    return [(r[h.index('Player')], r[h.index('Team')]) for r in d['leaderboard']['rows']], d.get('logos', {})


def read_js_value(path, var):
    """Like read_js_object but also accepts arrays / null."""
    if not os.path.exists(path):
        return None
    with open(path, encoding='utf-8') as f:
        txt = f.read()
    m = re.search(r'window\.' + var + r'\s*=\s*(.*?);\s*$', txt, re.S)
    try:
        return json.loads(m.group(1)) if m else None
    except ValueError:
        return None


def previous_elos():
    """player_id -> ELO from the last saved check (for the daily +/- column)."""
    prev, when = {}, None
    old = read_js_value(OUT, 'EOS_FACEIT') or {}
    when = old.get('updated')
    for p in (old.get('top') or []) + (read_js_value(OUT_REST, 'EOS_FACEIT_REST') or []) + (old.get('league') or []):
        if p.get('id') and p.get('elo') is not None:
            prev[p['id']] = p['elo']
    return prev, when


def write_js(path, var, value):
    with open(path, 'w', encoding='utf-8') as f:
        f.write('// Generated by scripts/fetch_faceit.py (daily GitHub Action) - do not edit by hand.\n')
        f.write('window.' + var + ' = ')
        json.dump(value, f, ensure_ascii=False, separators=(',', ':'))
        f.write(';\n')


def main():
    if not KEY:
        sys.exit('FACEIT_API_KEY is not set')
    prev, prev_when = previous_elos()

    top = []
    for offset in range(0, TOP_N, PAGE):
        data = get('/rankings/games/cs2/regions/EU', country='fi', offset=offset, limit=PAGE) or {}
        items = data.get('items') or []
        for i, it in enumerate(items):
            top.append({
                'pos': it.get('position') or offset + i + 1,
                'nick': it.get('nickname'),
                'elo': it.get('faceit_elo'),
                'lvl': it.get('game_skill_level'),
                'id': it.get('player_id'),
            })
        if len(items) < PAGE:
            break
    by_id = {p['id']: p for p in top}

    names = read_js_object(NAMES, 'EOS_FACEIT_NAMES') if os.path.exists(NAMES) else {}
    league, missing = [], []
    players, logos = eos_data()
    for player, team in players:
        manual = (names.get(player) or '').strip()
        nick = manual or player
        prof = get('/players', nickname=nick, game='cs2')
        if not prof and nick != nick.lower():
            prof = get('/players', nickname=nick.lower(), game='cs2')
        if not prof:
            league.append({'player': player, 'team': team, 'nick': None})
            missing.append(player)
            continue
        cs2 = (prof.get('games') or {}).get('cs2') or {}
        country = (prof.get('country') or '').lower()
        # A guessed nickname (the in-game name) is only trusted for a Finnish account
        # with CS2 ELO; other matches are usually someone else with the same name.
        if not manual and (country != 'fi' or not cs2.get('faceit_elo')):
            league.append({'player': player, 'team': team, 'nick': None, 'guess': prof.get('nickname'), 'guessCountry': country})
            missing.append(player)
            continue
        pid = prof.get('player_id')
        pos = by_id[pid]['pos'] if pid in by_id else None
        if pos is None and pid and (prof.get('country') or '').lower() == 'fi':
            rk = get('/rankings/games/cs2/regions/EU/players/' + quote(pid), country='fi', limit=1) or {}
            pos = rk.get('position')
        pos = pos or None  # 0 = unranked
        league.append({
            'player': player, 'team': team, 'nick': prof.get('nickname'),
            'elo': cs2.get('faceit_elo'), 'lvl': cs2.get('skill_level'),
            'pos': pos, 'country': country, 'id': pid,
        })

    # ELO change since yesterday: on the first run of a new (Finnish) day, the last saved
    # values become the baseline; later runs that day keep comparing with it.
    today = datetime.now(ZoneInfo('Europe/Helsinki')).date().isoformat()
    try:
        with open(BASE, encoding='utf-8') as f:
            base = json.load(f)
    except (OSError, ValueError):
        base = {}
    if base.get('date') != today:
        base = {'date': today, 'since': prev_when, 'elos': prev}
        with open(BASE, 'w', encoding='utf-8') as f:
            json.dump(base, f, separators=(',', ':'))
    base_elos = base.get('elos') or {}
    for p in top + league:
        if p.get('id') in base_elos and p.get('elo') is not None:
            p['d'] = p['elo'] - base_elos[p['id']]

    now = datetime.now(timezone.utc)
    out = {
        'updated': now.strftime('%Y-%m-%d %H:%M UTC'),
        'v': now.strftime('%Y%m%d%H%M%S'),
        'since': base.get('since'),
        'total': len(top),
        'logos': logos,
        'top': top[:FIRST_N],
        'league': league,
    }
    write_js(OUT, 'EOS_FACEIT', out)
    write_js(OUT_REST, 'EOS_FACEIT_REST', top[FIRST_N:])
    print(f'Wrote {OUT}: {len(top)} ranked Finnish players, {len(league) - len(missing)}/{len(league)} EOS players found')
    if missing:
        print('Not found on FACEIT (set their nickname in faceit-names.js):', ', '.join(missing))


if __name__ == '__main__':
    main()
